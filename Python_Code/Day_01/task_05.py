# round(): fn use for round off number. that takes two or one input number and round off after want to 

number = float(input("Enter Number That You Want to Round Off: "))  #takes input from and convert into float

result = round(number, 3)   # round off upto 3 digit after decimal

# print(type(result))   # round off fn result type is <class 'float'>

print(result)


